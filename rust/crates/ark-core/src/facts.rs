//! The fact hash of `services/memory/src/suggestions.ts` (`foldFact` and `hashOf`). A forgotten fact stores this hash in
//! `denied_facts`, so ARK never suggests the same fact again. The same fact in other letters, spaces or width has the same hash.

use unicode_normalization::UnicodeNormalization;

use crate::js::{collapse_runs, is_js_space, trim};

/// `text.normalize("NFKC").toLowerCase().replace(/\s+/g, " ").replace(/[.。]+$/u, "").trim()`.
pub fn fold_fact(text: &str) -> String {
    let lower: String = text.nfkc().collect::<String>().to_lowercase();
    let spaced = collapse_runs(&lower, is_js_space);
    trim(spaced.trim_end_matches(['.', '。'])).to_string()
}

/// The first 32 hex digits of the SHA-256 of the folded fact.
pub fn fact_hash(text: &str) -> String {
    let mut hex = sha256(fold_fact(text).as_bytes()).iter().map(|b| format!("{b:02x}")).collect::<String>();
    hex.truncate(32);
    hex
}

